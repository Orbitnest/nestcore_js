import type { DatabaseClient } from './database';

/** Postgres type → TypeScript type. Unknown types fall back to `unknown`. */
const PG_TO_TS: Record<string, string> = {
  int2: 'number', int4: 'number', int8: 'number',
  smallint: 'number', integer: 'number', bigint: 'number', serial: 'number', bigserial: 'number',
  numeric: 'number', decimal: 'number', real: 'number', float4: 'number', float8: 'number',
  'double precision': 'number',
  bool: 'boolean', boolean: 'boolean',
  text: 'string', varchar: 'string', 'character varying': 'string',
  char: 'string', character: 'string', bpchar: 'string', citext: 'string', uuid: 'string',
  name: 'string',
  date: 'string', timestamp: 'string', timestamptz: 'string',
  'timestamp with time zone': 'string', 'timestamp without time zone': 'string',
  time: 'string', timetz: 'string', interval: 'string',
  json: 'Record<string, unknown>', jsonb: 'Record<string, unknown>',
  bytea: 'string',
};

function tsType(pgType: string): string {
  const t = (pgType || '').toLowerCase().trim();
  if (!t) return 'unknown';
  if (t.endsWith('[]')) return `${tsType(t.slice(0, -2))}[]`;
  if (t.startsWith('_')) return `${tsType(t.slice(1))}[]`; // pg internal array name, e.g. _text
  return PG_TO_TS[t] ?? 'unknown';
}

function pascalCase(name: string): string {
  return name
    .replace(/(^|[_\- ])([a-zA-Z0-9])/g, (_m, _s, c) => c.toUpperCase())
    .replace(/[^a-zA-Z0-9]/g, '');
}

function fieldKey(name: string): string {
  return /^[a-zA-Z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

export interface GenerateTypesOptions {
  /** Only include these tables (default: all non-internal). */
  tables?: string[];
  /** Tables to skip (default: `auth_*` and `_*` internal tables). */
  exclude?: RegExp;
}

/** Loosely-typed metadata shapes — tolerant of how the endpoint wraps results. */
type Col = { name: string; type: string; nullable?: boolean };
function columnsOf(meta: unknown): Col[] {
  const m = meta as { columns?: Col[] } | Col[] | { data?: { columns?: Col[] } } | null;
  if (!m) return [];
  if (Array.isArray(m)) return (m[0] as { columns?: Col[] })?.columns ?? [];
  if (Array.isArray((m as { columns?: Col[] }).columns)) return (m as { columns: Col[] }).columns;
  if ((m as { data?: { columns?: Col[] } }).data?.columns) return (m as { data: { columns: Col[] } }).data.columns;
  return [];
}

/**
 * Introspect the project schema and emit TypeScript row interfaces plus a
 * `Database` map. Pair the output with `db.query<MyRow>(...)` or the query
 * builder for end-to-end type safety — OrbitNest's answer to
 * `supabase gen types typescript`.
 *
 * ```ts
 * import { writeFileSync } from 'fs';
 * writeFileSync('orbitnest.types.ts', await generateTypes(client.db));
 * ```
 */
export async function generateTypes(db: DatabaseClient, opts: GenerateTypesOptions = {}): Promise<string> {
  const listed = await db.listTables();
  if (listed.error) throw new Error(`generateTypes: could not list tables: ${listed.error.message}`);

  const raw = listed.data as unknown;
  let tables: string[] = Array.isArray(raw)
    ? (raw as unknown[]).map((t) => (typeof t === 'string' ? t : (t as { name?: string })?.name)).filter((t): t is string => !!t)
    : ((raw as { tables?: string[] })?.tables ?? []);

  const exclude = opts.exclude ?? /^(auth_|_)/;
  tables = opts.tables ? tables.filter((t) => opts.tables!.includes(t)) : tables.filter((t) => !exclude.test(t));
  tables = Array.from(new Set(tables)).sort();

  const blocks: string[] = [];
  const dbEntries: string[] = [];

  for (const table of tables) {
    const meta = await db.getTableMetadata(table);
    if (meta.error) continue;
    const cols = columnsOf(meta.data);
    if (cols.length === 0) continue;

    const fields = cols.map((c) => {
      const opt = c.nullable ? '?' : '';
      const nullable = c.nullable ? ' | null' : '';
      return `  ${fieldKey(c.name)}${opt}: ${tsType(c.type)}${nullable};`;
    });
    const iface = pascalCase(table);
    blocks.push(`export interface ${iface} {\n${fields.join('\n')}\n}`);
    dbEntries.push(`  ${JSON.stringify(table)}: ${iface};`);
  }

  const header =
    '// Generated by @orbitnest/node generateTypes — do not edit by hand.\n' +
    '// Re-run after schema changes to keep types in sync.\n';
  const dbMap = `export interface Database {\n${dbEntries.join('\n')}\n}`;
  return `${header}\n${blocks.join('\n\n')}\n\n${dbMap}\n`;
}

